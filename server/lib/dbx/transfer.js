'use strict';
// Moving data between databases: a full backup (JSON, gzip), loading a backup into any database,
// copying straight from one database to another, and a SQL script for each database type.
const crypto = require('node:crypto');
const zlib = require('node:zlib');
const { QUOTE, RESERVED, isoDateTime } = require('./dialects');

const FORMAT = 'sheet-metal-manager-backup';

// Tables in an order where every linked table comes before the table that links to it.
function loadOrder(tables) {
  const byName = new Map(tables.map((t) => [t.name, t]));
  const done = new Set(), out = [];
  const visit = (t, path = new Set()) => {
    if (done.has(t.name) || path.has(t.name)) return;
    path.add(t.name);
    for (const c of t.cols.filter((x) => x.ref && x.ref !== t.name)) if (byName.has(c.ref)) visit(byName.get(c.ref), path);
    done.add(t.name);
    out.push(t);
  };
  tables.forEach((t) => visit(t));
  return out;
}

// Every row of every table, with counts and a checksum so a copy can be checked later.
function dump(db, tables, { schemaVersion, app } = {}) {
  const data = {};
  for (const t of tables) {
    const have = new Set(db.columns(t.name));
    if (!have.size) { data[t.name] = []; continue; }
    const order = t.cols.some((c) => c.name === 'id') ? ' ORDER BY id' : '';
    data[t.name] = db.prepare(`SELECT * FROM ${t.name}${order}`).all().map((r) => ({ ...r }));
  }
  const counts = Object.fromEntries(Object.entries(data).map(([k, v]) => [k, v.length]));
  const body = JSON.stringify(data);
  return { format: FORMAT, version: 1, app: app || null, schema_version: schemaVersion || null, source: db.dialect,
    created_at: `${isoDateTime(new Date())} UTC`, counts, sha256: crypto.createHash('sha256').update(body).digest('hex'), tables: data };
}

const gzip = (backup) => zlib.gzipSync(Buffer.from(JSON.stringify(backup)), { level: 9 });
function readBackup(buf) {
  const text = buf[0] === 0x1f && buf[1] === 0x8b ? zlib.gunzipSync(buf).toString('utf8') : buf.toString('utf8');
  const b = JSON.parse(text);
  if (b.format !== FORMAT) throw new Error('This file is not a Sheet Metal Manager backup');
  const sum = crypto.createHash('sha256').update(JSON.stringify(b.tables)).digest('hex');
  if (b.sha256 && sum !== b.sha256) throw new Error('The backup is damaged: its checksum does not match');
  return b;
}

// Puts the identity / auto-number counters past the highest id after rows were loaded with their own ids.
function fixCounters(db, t) {
  if (!t.cols.some((c) => c.type === 'id')) return;
  const max = (db.prepare(`SELECT MAX(id) AS m FROM ${t.name}`).get() || {}).m || 0;
  const q = (w) => (RESERVED[db.dialect] && RESERVED[db.dialect].includes(w) ? QUOTE[db.dialect](w) : w);
  if (db.dialect === 'postgres') db.raw(`SELECT setval(pg_get_serial_sequence('${q(t.name)}', 'id'), ${Math.max(max, 1)}, ${max > 0})`);
  if (db.dialect === 'oracle') db.raw(`ALTER TABLE ${q(t.name)} MODIFY id GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH ${max + 1})`);
  if (db.dialect === 'mysql') db.raw(`ALTER TABLE ${q(t.name)} AUTO_INCREMENT = ${max + 1}`);
}

// Loads a backup into an (empty or emptied) database that already has the tables.
function load(db, tables, backup, { replace = false } = {}) {
  const order = loadOrder(tables);
  const q = (w) => (RESERVED[db.dialect] && RESERVED[db.dialect].includes(w) ? QUOTE[db.dialect](w) : w);
  const existing = order.filter((t) => (db.prepare(`SELECT COUNT(*) AS n FROM ${t.name}`).get() || {}).n > 0);
  if (existing.length && !replace) {
    throw new Error(`The target database already has data (${existing.map((t) => t.name).join(', ')}). Use --replace to overwrite it.`);
  }
  // Empty the tables first, children before parents.
  for (const t of [...order].reverse()) db.prepare(`DELETE FROM ${t.name}`).run();
  const loaded = {};
  for (const t of order) {
    const rows = backup.tables[t.name] || [];
    const cols = new Set(db.columns(t.name));
    const identity = db.dialect === 'mssql' && t.cols.some((c) => c.type === 'id');
    try {
      db.exec('BEGIN');
      // SQL Server keeps this setting only for the connection of the open transaction.
      if (identity && rows.length) db.raw(`SET IDENTITY_INSERT ${q(t.name)} ON`);
      for (const r of rows) {
        const keys = Object.keys(r).filter((k) => cols.has(k.toLowerCase()));
        db.prepare(`INSERT INTO ${t.name} (${keys.join(', ')}) VALUES (${keys.map(() => '?').join(', ')})`).run(...keys.map((k) => r[k]));
      }
      if (identity && rows.length) db.raw(`SET IDENTITY_INSERT ${q(t.name)} OFF`);
      db.exec('COMMIT');
    } catch (err) {
      try { db.exec('ROLLBACK'); } catch { /* nothing open */ }
      throw new Error(`Loading ${t.name} failed: ${err.message}`);
    }
    if (rows.length) fixCounters(db, t);
    loaded[t.name] = rows.length;
  }
  return loaded;
}

// Row counts in the database compared with a backup; empty list = everything matches.
function verify(db, tables, backup) {
  const diff = [];
  for (const t of tables) {
    const want = (backup.tables[t.name] || []).length;
    const got = (db.prepare(`SELECT COUNT(*) AS n FROM ${t.name}`).get() || {}).n;
    if (Number(got) !== want) diff.push({ table: t.name, backup: want, database: Number(got) });
  }
  return diff;
}

// A .sql file that builds the tables and fills them, for the chosen database type.
function sqlScript(dialect, backup, tables, createStatements) {
  const q = (w) => (dialect !== 'sqlite' && RESERVED[dialect].includes(w) ? QUOTE[dialect](w) : w);
  const lit = (v) => {
    if (v === null || v === undefined) return 'NULL';
    if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL';
    const s = String(v).replace(/'/g, "''");
    if (dialect === 'oracle' && s.length > 3900) {
      // Oracle string literals stop at 4000 characters; long text is joined from pieces.
      return `TO_CLOB('${s.match(/[\s\S]{1,3900}/g).join("') || TO_CLOB('")}')`;
    }
    return dialect === 'mssql' ? `N'${s}'` : `'${s}'`;
  };
  const end = dialect === 'mssql' ? '\nGO' : ';';
  const lines = [`-- Sheet Metal Manager data for ${dialect}, made ${backup.created_at} from ${backup.source}.`,
    '-- Run on an empty database. Tables, indexes and links are created first, then the rows are added.', ''];
  if (dialect === 'mysql') lines.push("SET sql_mode = CONCAT(@@sql_mode, ',PIPES_AS_CONCAT');", 'SET FOREIGN_KEY_CHECKS = 0;');
  if (dialect === 'sqlite') lines.push('PRAGMA foreign_keys = OFF;', 'BEGIN;');
  if (dialect === 'mssql') lines.push('SET QUOTED_IDENTIFIER ON\nGO', 'SET ANSI_NULLS ON\nGO');
  if (dialect === 'oracle') lines.push('SET DEFINE OFF', 'WHENEVER SQLERROR EXIT FAILURE');
  for (const s of createStatements) lines.push(`${s}${end}`);
  for (const t of loadOrder(tables)) {
    const rows = backup.tables[t.name] || [];
    if (!rows.length) continue;
    const identity = dialect === 'mssql' && t.cols.some((c) => c.type === 'id');
    if (identity) lines.push(`SET IDENTITY_INSERT ${q(t.name)} ON${end}`);
    for (const r of rows) {
      const keys = Object.keys(r);
      lines.push(`INSERT INTO ${q(t.name)} (${keys.map(q).join(', ')}) VALUES (${keys.map((k) => lit(r[k])).join(', ')})${end}`);
    }
    if (identity) lines.push(`SET IDENTITY_INSERT ${q(t.name)} OFF${end}`);
    const max = Math.max(0, ...rows.map((r) => Number(r.id) || 0));
    if (t.cols.some((c) => c.type === 'id') && max) {
      if (dialect === 'postgres') lines.push(`SELECT setval(pg_get_serial_sequence('${q(t.name)}', 'id'), ${max});`);
      if (dialect === 'mysql') lines.push(`ALTER TABLE ${q(t.name)} AUTO_INCREMENT = ${max + 1};`);
      if (dialect === 'oracle') lines.push(`ALTER TABLE ${q(t.name)} MODIFY id GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH ${max + 1});`);
    }
  }
  if (dialect === 'mysql') lines.push('SET FOREIGN_KEY_CHECKS = 1;');
  if (dialect === 'sqlite') lines.push('COMMIT;', 'PRAGMA foreign_keys = ON;');
  if (dialect === 'oracle') lines.push('COMMIT;');
  return `${lines.join('\n')}\n`;
}

module.exports = { dump, load, verify, gzip, readBackup, sqlScript, loadOrder, FORMAT };
