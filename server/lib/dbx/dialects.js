// SQL dialects. The app writes SQLite-style SQL; translate() turns it into each database's own SQL,
// and the column types / DDL below build the same tables everywhere.

// Reserved words that are also column, table or alias names in this app. Only these are quoted.
const RESERVED = {
  postgres: ['user', 'order', 'group', 'limit', 'offset', 'end', 'check', 'default', 'table', 'column', 'current_date'],
  mysql: ['key', 'condition', 'procedure', 'before', 'range', 'rows', 'row', 'rank', 'groups', 'interval', 'release', 'usage', 'match', 'option', 'lock', 'load', 'read', 'reads', 'order', 'group', 'limit', 'check', 'default', 'table', 'column'],
  mssql: ['key', 'procedure', 'file', 'current', 'user', 'plan', 'option', 'percent', 'open', 'close', 'rule', 'precision', 'order', 'group', 'check', 'default', 'table', 'column', 'size'],
  oracle: ['date', 'size', 'file', 'level', 'mode', 'comment', 'session', 'user', 'rows', 'row', 'number', 'access', 'resource', 'start', 'option', 'current', 'initial', 'online', 'share', 'uid', 'audit', 'order', 'group', 'check', 'default', 'table', 'column', 'uid', 'successful', 'raw', 'long', 'lock', 'validate', 'synonym', 'privileges', 'key'],
};

const QUOTE = { postgres: (w) => `"${w}"`, mysql: (w) => `\`${w}\``, mssql: (w) => `[${w}]`, oracle: (w) => `"${w}"` };

// Column types: id (auto number key), int, real, key (short text that is indexed), text (any length), long (very long text).
const TYPES = {
  sqlite: { id: 'INTEGER PRIMARY KEY', int: 'INTEGER', real: 'REAL', key: 'TEXT', text: 'TEXT', long: 'TEXT' },
  postgres: { id: 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', int: 'INTEGER', real: 'DOUBLE PRECISION', key: 'TEXT', text: 'TEXT', long: 'TEXT' },
  mysql: { id: 'INT AUTO_INCREMENT PRIMARY KEY', int: 'INT', real: 'DOUBLE', key: 'VARCHAR(255)', text: 'LONGTEXT', long: 'LONGTEXT' },
  mssql: { id: 'INT IDENTITY(1,1) PRIMARY KEY', int: 'INT', real: 'FLOAT', key: 'NVARCHAR(200)', text: 'NVARCHAR(MAX)', long: 'NVARCHAR(MAX)' },
  oracle: { id: 'NUMBER(10) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY', int: 'NUMBER(10)', real: 'BINARY_DOUBLE', key: 'VARCHAR2(450 CHAR)', text: 'VARCHAR2(4000 CHAR)', long: 'CLOB' },
};

// "Now" as 'YYYY-MM-DD HH:MM:SS' in UTC, for column defaults.
const NOW_DEFAULT = {
  sqlite: "(datetime('now'))",
  postgres: "(to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))",
  mysql: "(DATE_FORMAT(UTC_TIMESTAMP(), '%Y-%m-%d %H:%i:%s'))",
  mssql: '(CONVERT(varchar(19), SYSUTCDATETIME(), 120))',
  oracle: "TO_CHAR(SYS_EXTRACT_UTC(SYSTIMESTAMP), 'YYYY-MM-DD HH24:MI:SS')",
};

const pad = (n) => String(n).padStart(2, '0');
const isoDate = (d) => `${d.getUTCFullYear()}-${pad(d.getUTCMonth() + 1)}-${pad(d.getUTCDate())}`;
const isoDateTime = (d) => `${isoDate(d)} ${pad(d.getUTCHours())}:${pad(d.getUTCMinutes())}:${pad(d.getUTCSeconds())}`;

// SQLite date('now', ...) and datetime('now', ...) worked out here, as a literal.
function sqliteNow(fn, mods) {
  let d = new Date();
  for (const m of mods) {
    if (m === 'localtime') d = new Date(d.getTime() - d.getTimezoneOffset() * 60000);
    const off = /^([+-]?\d+) (day|hour|minute)s?$/.exec(m);
    if (off) d = new Date(d.getTime() + Number(off[1]) * { day: 86400000, hour: 3600000, minute: 60000 }[off[2]]);
  }
  return `'${fn === 'date' ? isoDate(d) : isoDateTime(d)}'`;
}

// Splits SQL into string literals and code, so changes never touch text inside quotes.
function pieces(sql) {
  const out = [];
  let i = 0, start = 0;
  while (i < sql.length) {
    if (sql[i] === "'") {
      if (i > start) out.push({ code: sql.slice(start, i) });
      let j = i + 1;
      while (j < sql.length) { if (sql[j] === "'" && sql[j + 1] === "'") j += 2; else if (sql[j] === "'") break; else j++; }
      out.push({ lit: sql.slice(i, j + 1) });
      i = start = j + 1;
    } else i++;
  }
  if (start < sql.length) out.push({ code: sql.slice(start) });
  return out;
}
const join = (ps) => ps.map((p) => p.code ?? p.lit).join('');
const mapCode = (sql, fn) => join(pieces(sql).map((p) => (p.code !== undefined ? { code: fn(p.code) } : p)));

// Splits a script on ; outside quotes.
function splitStatements(sql) {
  const out = [];
  let cur = '';
  for (const p of pieces(sql)) {
    if (p.lit !== undefined) { cur += p.lit; continue; }
    const parts = p.code.split(';');
    cur += parts[0];
    for (const x of parts.slice(1)) { out.push(cur); cur = x; }
  }
  out.push(cur);
  return out.map((s) => s.replace(/^\s*--[^\n]*\n/gm, '').trim()).filter(Boolean);
}

// Finds the closing bracket for the "(" at index open (literals already masked).
function closeAt(s, open) {
  let depth = 0;
  for (let i = open; i < s.length; i++) {
    if (s[i] === '(') depth++;
    else if (s[i] === ')' && --depth === 0) return i;
  }
  return -1;
}
function topLevelArgs(inner) {
  const args = [];
  let depth = 0, cur = '';
  for (const ch of inner) {
    if (ch === '(') depth++;
    if (ch === ')') depth--;
    if (ch === ',' && depth === 0) { args.push(cur); cur = ''; } else cur += ch;
  }
  args.push(cur);
  return args;
}

// Literals are swapped for placeholders while the code is rewritten, then put back.
function masked(sql, fn) {
  const lits = [];
  const code = join(pieces(sql).map((p) => (p.lit !== undefined ? { code: `\u0001${lits.push(p.lit) - 1}\u0001` } : p)));
  return fn(code).replace(/\u0001(\d+)\u0001/g, (_, i) => lits[Number(i)]);
}

// SQLite's two-argument MIN(a, b) and MAX(a, b) are LEAST and GREATEST elsewhere.
function scalarMinMax(s) {
  const re = /\b(MIN|MAX)\s*\(/gi;
  let m;
  while ((m = re.exec(s))) {
    const open = m.index + m[0].length - 1, close = closeAt(s, open);
    if (close < 0) break;
    if (topLevelArgs(s.slice(open + 1, close)).length > 1) {
      s = `${s.slice(0, m.index)}${m[1].toUpperCase() === 'MIN' ? 'LEAST' : 'GREATEST'}${s.slice(m.index + m[1].length)}`;
    }
    re.lastIndex = m.index + 1;
  }
  return s;
}

// GROUP_CONCAT([DISTINCT] x [, sep]) in each database's words.
function groupConcat(s, dialect) {
  const re = /\bGROUP_CONCAT\s*\(/gi;
  let m;
  while ((m = re.exec(s))) {
    const open = m.index + m[0].length - 1, close = closeAt(s, open);
    if (close < 0) break;
    const args = topLevelArgs(s.slice(open + 1, close));
    let x = args[0].trim();
    const sep = args[1] ? args[1].trim() : "','";
    const distinct = /^DISTINCT\s+/i.test(x);
    x = x.replace(/^DISTINCT\s+/i, '');
    const d = distinct ? 'DISTINCT ' : '';
    const rep = dialect === 'postgres' ? `STRING_AGG(${d}CAST(${x} AS TEXT), ${sep})`
      : dialect === 'mysql' ? `GROUP_CONCAT(${d}${x} SEPARATOR ${sep})`
        : dialect === 'mssql' ? `STRING_AGG(CAST(${x} AS NVARCHAR(MAX)), ${sep})`
          : `LISTAGG(${d}${x}, ${sep}) WITHIN GROUP (ORDER BY ${x})`;
    s = s.slice(0, m.index) + rep + s.slice(close + 1);
    re.lastIndex = m.index + rep.length;
  }
  return s;
}

// LIMIT n for SQL Server: TOP (n), or OFFSET/FETCH after an ORDER BY.
function mssqlLimit(s) {
  const re = /\bLIMIT\s+(\d+)/i;
  let m;
  while ((m = re.exec(s))) {
    // The SELECT this LIMIT belongs to: the nearest one before it at the same bracket depth.
    let depth = 0, sel = -1, ordered = false;
    for (let i = m.index - 1; i >= 0; i--) {
      if (s[i] === ')') depth++;
      else if (s[i] === '(') { if (depth === 0) break; depth--; }
      if (depth === 0 && /^ORDER\s+BY\b/i.test(s.slice(i)) && /\W/.test(s[i - 1] || ' ')) ordered = true;
      if (depth === 0 && /^SELECT\b/i.test(s.slice(i)) && /\W/.test(s[i - 1] || ' ')) { sel = i; break; }
    }
    if (ordered || sel < 0) s = `${s.slice(0, m.index)}OFFSET 0 ROWS FETCH NEXT ${m[1]} ROWS ONLY${s.slice(m.index + m[0].length)}`;
    else {
      const after = s.slice(sel + 6).match(/^\s+DISTINCT\b/i);
      const at = sel + 6 + (after ? after[0].length : 0);
      s = `${s.slice(0, at)} TOP (${m[1]})${s.slice(at, m.index)}${s.slice(m.index + m[0].length)}`;
    }
  }
  return s;
}

// Rewrites one SQLite-style statement for another database.
// Returns { sql, orIgnore, orReplace: { table, cols } } — the adapter handles the last two.
function translate(sql, dialect, idents) {
  if (dialect === 'sqlite') return { sql };
  const out = {};
  let s = sql.trim();
  // date('now', ...) and datetime('now', ...) become literals worked out now.
  s = s.replace(/\b(date|datetime)\(\s*'now'((?:\s*,\s*'[^']*')*)\s*\)/gi, (_, fn, rest) =>
    sqliteNow(fn.toLowerCase(), [...rest.matchAll(/'([^']*)'/g)].map((x) => x[1])));
  const ins = /^INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO\s+(\w+)\s*\(([^)]*)\)/i.exec(s);
  if (ins) {
    s = s.replace(/^INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO/i, 'INSERT INTO');
    if (ins[1].toUpperCase() === 'IGNORE') out.orIgnore = true;
    else out.orReplace = { table: ins[2], cols: ins[3].split(',').map((c) => c.trim()) };
  }
  const q = QUOTE[dialect];
  const reserved = new Set(RESERVED[dialect].filter((w) => idents.has(w)));
  s = masked(s, (c) => {
    c = c.replace(/(CAST\([^()]*\)|[\w.]+)\s*=\s*\?\s+COLLATE\s+NOCASE/gi, 'LOWER($1) = LOWER(?)').replace(/\s+COLLATE\s+NOCASE/gi, '');
    c = scalarMinMax(c);
    c = groupConcat(c, dialect);
    if (dialect === 'mysql') c = c.replace(/\bAS\s+TEXT\s*\)/gi, 'AS CHAR)');
    if (dialect === 'mssql') c = c.replace(/\bAS\s+TEXT\s*\)/gi, 'AS NVARCHAR(450))').replace(/\bsubstr\s*\(/gi, 'SUBSTRING(').replace(/\bLENGTH\s*\(/gi, 'LEN(');
    if (dialect === 'oracle') c = c.replace(/CAST\(([^()]*)\s+AS\s+TEXT\s*\)/gi, 'TO_CHAR($1)').replace(/\bLIMIT\s+(\d+)/gi, 'FETCH FIRST $1 ROWS ONLY');
    if (dialect === 'postgres') c = c.replace(/\bLIKE\s+\?/gi, 'ILIKE ?');
    if (dialect === 'mssql') c = mssqlLimit(c);
    // Quote reserved words used as names, e.g. a column called "key" or "date".
    if (reserved.size) c = c.replace(/(^|[^\w"`\[])([A-Za-z_]\w*)(?![\w"`\]])/g, (all, pre, w, at, whole) =>
      (reserved.has(w.toLowerCase()) && whole[at + all.length] !== '(' ? `${pre}${q(w.toLowerCase())}` : all));
    // Placeholders: ? becomes $1, @p1 or :1.
    let n = 0;
    if (dialect === 'postgres') c = c.replace(/\?/g, () => `$${++n}`);
    if (dialect === 'mssql') c = c.replace(/\?/g, () => `@p${++n}`);
    if (dialect === 'oracle') c = c.replace(/\?/g, () => `:${++n}`);
    return c;
  });
  out.sql = s;
  return out;
}

